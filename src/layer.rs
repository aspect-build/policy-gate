type LimitFuture<F, T, C, A, M, R, D> = Either<
    EnforcedResponseFuture<F, T, C, A, M, R, D>,
    BoxFuture<'static, Result<Response<<A as BodyAdapter>::Body>, Infallible>>,
>;

impl<S, ResBody, P, T, C, A, M, R, D> tower::Service<Request<A::Body>>
    for PolicyGateMiddleware<S, P, T, C, A, M, R, D>
where
    P: RequestPolicy<T>,
    T: Subject,
    C: DecisionSource<T> + 'static,
    A: BodyAdapter,
    M: PolicyGateMetrics,
    R: RejectionResponse<A>,
    D: TimeDriver,
    S: tower::Service<Request<A::Body>, Response = Response<ResBody>, Error = Infallible>
        + Clone
        + Send
        + 'static,
    S::Future: Send + 'static,
    ResBody: Body<Data = Bytes> + Send + 'static,
    ResBody::Error: Into<Box<dyn core::error::Error + Send + Sync>>,
{
    type Response = Response<A::Body>;
    type Error = Infallible;
    type Future = LimitFuture<S::Future, T, C, A, M, R, D>;

    fn poll_ready(&mut self, cx: &mut Context<'_>) -> Poll<Result<(), Self::Error>> {
        self.inner.poll_ready(cx)
    }

    fn call(&mut self, request: Request<A::Body>) -> Self::Future {
        let Some(subject) = self.policy.subject(&request) else {
            self.context.metrics.missing_subject_rejection();
            if should_log_missing_subject() {
                tracing::warn!("verified request carries no subject id");
            }
            return Either::Right(Box::pin(ready(Ok(self
                .response
                .missing_subject(self.body, &self.context.missing_subject_message)))));
        };

        let refresh_disabled = self.context.gate.refresh_disabled();
        if refresh_disabled {
            if let Some(admission) = self.context.gate.try_cached_now(&subject) {
                if admission.is_allowed() {
                    return Either::Left(pass_through(
                        &mut self.inner,
                        request,
                        subject,
                        admission,
                        Arc::clone(&self.context),
                        self.policy.as_ref(),
                        ResponseContext {
                            body: self.body,
                            response: self.response,
                        },
                    ));
                }
                if admission.state() == AdmissionState::Denied {
                    return Either::Right(Box::pin(ready(Ok(deny(
                        &self.context,
                        self.body,
                        self.response,
                    )))));
                }
            }
            self.context.metrics.snapshot_miss();
        }

        // We must take the current `inner` and not the clone.
        // See: https://docs.rs/tower/latest/tower/trait.Service.html#be-careful-when-cloning-inner-services
        let clone = self.inner.clone();
        let mut inner = core::mem::replace(&mut self.inner, clone);
        let context = Arc::clone(&self.context);
        let policy = Arc::clone(&self.policy);
        let body = self.body;
        let response = self.response;
        Either::Right(Box::pin(async move {
            loop {
                match context.gate.admit(&subject).await {
                    Ok(admission) if admission.is_allowed() => {
                        return pass_through(
                            &mut inner,
                            request,
                            subject,
                            admission,
                            Arc::clone(&context),
                            policy.as_ref(),
                            ResponseContext { body, response },
                        )
                        .await;
                    }
                    Ok(admission) if admission.state() == AdmissionState::Denied => {
                        return Ok(deny(&context, body, response));
                    }
                    // A concurrent invalidation requires recovery, not a policy rejection.
                    Ok(_) => {}
                    Err(error) => {
                        context.metrics.unavailable_rejection();
                        return Ok(response.unavailable(body, error, UNAVAILABLE_MESSAGE));
                    }
                }
            }
        }))
    }
}

/// Unboxed snapshot-hit future that wraps the response stream.
#[pin_project::pin_project]
pub struct EnforcedResponseFuture<
    F,
    T: Subject,
    C: DecisionSource<T>,
    A: BodyAdapter,
    M: PolicyGateMetrics,
    R: RejectionResponse<A>,
    D,
> {
    #[pin]
    inner: F,
    subject: T,
    admission: Option<Admission<D>>,
    context: Arc<GateContext<T, C, M, D>>,
    body: A,
    response: R,
    enforce_response_body: bool,
}

impl<
    F,
    T: Subject,
    C: DecisionSource<T>,
    A: BodyAdapter,
    M: PolicyGateMetrics,
    R: RejectionResponse<A>,
    D: TimeDriver,
> core::fmt::Debug for EnforcedResponseFuture<F, T, C, A, M, R, D>
{
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        f.debug_struct("EnforcedResponseFuture")
            .finish_non_exhaustive()
    }
}

impl<F, ResBody, T, C, A, M, R, D> Future for EnforcedResponseFuture<F, T, C, A, M, R, D>
where
    T: Subject,
    C: DecisionSource<T> + 'static,
    A: BodyAdapter,
    M: PolicyGateMetrics,
    R: RejectionResponse<A>,
    D: TimeDriver,
    F: Future<Output = Result<Response<ResBody>, Infallible>>,
    ResBody: Body<Data = Bytes> + Send + 'static,
    ResBody::Error: Into<Box<dyn core::error::Error + Send + Sync>>,
{
    type Output = Result<Response<A::Body>, Infallible>;

    fn poll(self: Pin<&mut Self>, cx: &mut Context<'_>) -> Poll<Self::Output> {
        let this = self.project();
        let response = ready!(this.inner.poll(cx))?;
        let admission = this
            .admission
            .take()
            .expect("response future completes once");
        let response = if *this.enforce_response_body {
            let (mut parts, body) = response.into_parts();
            // GateContext may truncate the body, so an original exact length is no longer valid.
            parts.headers.remove(CONTENT_LENGTH);
            Response::from_parts(
                parts,
                this.body.adapt(EnforcedBody::new(
                    body,
                    (*this.subject).clone(),
                    admission,
                    Arc::clone(this.context),
                    *this.response,
                    BodySide::Response,
                )),
            )
        } else {
            response.map(|body| this.body.adapt(body))
        };
        Poll::Ready(Ok(response))
    }
}

fn pass_through<S, ResBody, P, T, C, A, M, R, D>(
    inner: &mut S,
    request: Request<A::Body>,
    subject: T,
    admission: Admission<D>,
    context: Arc<GateContext<T, C, M, D>>,
    policy: &P,
    response_context: ResponseContext<A, R>,
) -> EnforcedResponseFuture<S::Future, T, C, A, M, R, D>
where
    P: RequestPolicy<T>,
    T: Subject,
    C: DecisionSource<T> + 'static,
    A: BodyAdapter,
    M: PolicyGateMetrics,
    R: RejectionResponse<A>,
    D: TimeDriver,
    S: tower::Service<Request<A::Body>, Response = Response<ResBody>>,
{
    let ResponseContext {
        body: body_adapter,
        response,
    } = response_context;
    let enforce_request_body = policy.enforce_request_body(&request);
    let enforce_response_body = policy.enforce_response_body(&request);
    let request = if enforce_request_body {
        request.map(|body| {
            body_adapter.adapt(EnforcedBody::new(
                body,
                subject.clone(),
                admission.clone(),
                Arc::clone(&context),
                response,
                BodySide::Request,
            ))
        })
    } else {
        request
    };
    EnforcedResponseFuture {
        inner: inner.call(request),
        subject,
        admission: Some(admission),
        context,
        body: body_adapter,
        response,
        enforce_response_body,
    }
}

fn should_log_missing_subject() -> bool {
    let now = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .unwrap_or_default()
        .as_secs();
    let next = NEXT_MISSING_SUBJECT_LOG.load(Ordering::Relaxed);
    now >= next
        && NEXT_MISSING_SUBJECT_LOG
            .compare_exchange(
                next,
                now.saturating_add(MISSING_SUBJECT_LOG_INTERVAL_SECS),
                Ordering::Relaxed,
                Ordering::Relaxed,
            )
            .is_ok()
}

fn deny<
    T: Subject,
    C: DecisionSource<T>,
    A: BodyAdapter,
    M: PolicyGateMetrics,
    R: RejectionResponse<A>,
    D: TimeDriver,
>(
    context: &GateContext<T, C, M, D>,
    body: A,
    response: R,
) -> Response<A::Body> {
    context.metrics.denial();
    response.denied(body, &context.rejection_message)
}

fn http_response<A: BodyAdapter>(body: A, status: StatusCode, message: &str) -> Response<A::Body> {
    let mut response = Response::new(body.make_body(Bytes::copy_from_slice(message.as_bytes())));
    *response.status_mut() = status;
    response
}
