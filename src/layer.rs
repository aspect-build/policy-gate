impl<P, T, C, A, M, D> PolicyGateLayer<P, T, C, A, M, HttpRejectionResponse, D>
where
    P: RequestPolicy<T>,
    T: Subject,
    C: DecisionSource<T>,
    A: BodyAdapter,
    M: PolicyGateMetrics,
    D: TimeDriver,
{
    /// Constructs a layer over the transport-neutral gate with plain HTTP rejection rendering.
    ///
    /// The layer observes the gate; it neither owns nor polls the gate's watcher, which the caller
    /// must keep polled as described in the [runtime contract](crate#runtime-contract).
    #[must_use]
    pub fn new(
        gate: PolicyGate<T, C, M, D>,
        config: &PolicyGateLayerConfig,
        policy: P,
        body: A,
    ) -> Self {
        Self::new_with_response(gate, config, policy, body, HttpRejectionResponse)
    }
}

impl<P, T, C, A, M, R, D> PolicyGateLayer<P, T, C, A, M, R, D>
where
    P: RequestPolicy<T>,
    T: Subject,
    C: DecisionSource<T>,
    A: BodyAdapter,
    M: PolicyGateMetrics,
    R: RejectionResponse<A>,
    D: TimeDriver,
{
    /// Constructs a layer with caller-defined response rendering.
    ///
    /// Use it to render rejections for a non-plain-HTTP transport, such as
    /// `TonicRejectionResponse` from the `tonic-layer` feature.
    #[must_use]
    pub fn new_with_response(
        gate: PolicyGate<T, C, M, D>,
        config: &PolicyGateLayerConfig,
        policy: P,
        body: A,
        response: R,
    ) -> Self {
        let metrics = gate.metrics();
        Self {
            context: Arc::new(GateContext {
                gate,
                rejection_message: Arc::clone(&config.denied_message),
                missing_subject_message: Arc::clone(&config.missing_subject_message),
                metrics,
            }),
            policy: Arc::new(policy),
            body,
            response,
        }
    }

    /// Replaces the response callback while retaining the configured gate and policy.
    ///
    /// Only the unavailable-admission response changes; denial, missing-subject, and stream
    /// rejections keep their current rendering. The callback runs on the request path, so it must
    /// not block.
    #[must_use]
    pub fn with_unavailable_response<F>(
        self,
        unavailable_response: F,
    ) -> PolicyGateLayer<P, T, C, A, M, UnavailableResponseAdapter<R, F>, D>
    where
        F: Copy + Fn(AdmissionUnavailable) -> Response<A::Body> + Send + Sync + 'static,
    {
        PolicyGateLayer {
            context: self.context,
            policy: self.policy,
            body: self.body,
            response: UnavailableResponseAdapter {
                inner: self.response,
                unavailable: unavailable_response,
            },
        }
    }
}

