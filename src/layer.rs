/// Rejection messages used by the Tower layer.
///
/// The message for an unavailable decision source is fixed, because it describes a retryable
/// server condition rather than a policy outcome; replace that response wholesale with
/// [`PolicyGateLayer::with_unavailable_response`].
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct PolicyGateLayerConfig {
    denied_message: Arc<str>,
    missing_subject_message: Arc<str>,
}

impl PolicyGateLayerConfig {
    /// Creates the layer's rejection text.
    ///
    /// `denied_message` is returned for an authoritative denial, including the mid-stream cutoff
    /// of an already admitted request. `missing_subject_message` is returned when
    /// [`RequestPolicy::subject`] finds no subject on the request. Both messages reach clients, so
    /// keep them free of internal detail.
    #[must_use]
    pub fn new(
        denied_message: impl Into<Arc<str>>,
        missing_subject_message: impl Into<Arc<str>>,
    ) -> Self {
        Self {
            denied_message: denied_message.into(),
            missing_subject_message: missing_subject_message.into(),
        }
    }

    /// Returns the message rendered for an authoritative denial.
    #[must_use]
    pub fn denied_message(&self) -> &str {
        &self.denied_message
    }

    /// Returns the message rendered for a request that carries no subject.
    #[must_use]
    pub fn missing_subject_message(&self) -> &str {
        &self.missing_subject_message
    }
}

/// Host decisions needed by the context middleware.
///
/// One instance is shared by every request the layer handles, so the methods must be cheap,
/// side-effect free, and safe to call concurrently.
pub trait RequestPolicy<T: Subject>: Send + Sized + Sync + 'static {
    /// Returns the subject for this request.
    ///
    /// `None` rejects the request with the configured missing-subject response without consulting
    /// the gate. Resolve the subject from data already on the request, such as an extension
    /// inserted by an upstream authentication layer.
    fn subject<B>(&self, request: &Request<B>) -> Option<T>;

    /// Whether a mid-stream denial should reset the request body.
    ///
    /// Enable it for long-lived uploads and client-streaming RPCs, where a denial must interrupt
    /// data the client is still sending. Wrapping a body costs a policy check per frame.
    fn enforce_request_body<B>(&self, request: &Request<B>) -> bool;

    /// Whether a mid-stream denial should terminate the response body.
    ///
    /// Defaults to `true`. Enforcing the response body drops the `content-length` header, since a
    /// denial can truncate the body mid-flight; return `false` for responses that must keep an
    /// exact length.
    fn enforce_response_body<B>(&self, _request: &Request<B>) -> bool {
        true
    }
}

/// Converts arbitrary HTTP bodies into the single body type exposed by the layer.
///
/// The layer wraps request and response bodies to enforce mid-stream denials, which needs one
/// concrete body type for the whole stack. Implement this over the host framework's erased body —
/// the `axum-body` feature provides `AxumBodyAdapter` for Axum — and keep the adapter a
/// zero-sized handle.
pub trait BodyAdapter: Copy + Send + Sync + 'static {
    /// Body type accepted and returned by the wrapped service.
    type Body: Body<Data = Bytes, Error: Into<BoxBodyError>> + Send + 'static;

    /// Erases or otherwise adapts an arbitrary compatible body.
    fn adapt<B>(self, body: B) -> Self::Body
    where
        B: Body<Data = Bytes> + Send + 'static,
        B::Error: Into<BoxBodyError>;

    /// Creates a body containing response bytes generated by context.
    fn make_body(self, bytes: Bytes) -> Self::Body;
}

/// Axum's type-erased body adapter.
///
/// Requires the `axum-body` feature.
#[cfg(feature = "axum-body")]
#[derive(Clone, Copy, Debug, Default)]
pub struct AxumBodyAdapter;

#[cfg(feature = "axum-body")]
impl BodyAdapter for AxumBodyAdapter {
    type Body = axum_core::body::Body;

    fn adapt<B>(self, body: B) -> Self::Body
    where
        B: Body<Data = Bytes> + Send + 'static,
        B::Error: Into<BoxBodyError>,
    {
        axum_core::body::Body::new(body)
    }

    fn make_body(self, bytes: Bytes) -> Self::Body {
        axum_core::body::Body::from(bytes)
    }
}

/// Identifies which half of a streaming HTTP body was denied.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum BodySide {
    /// The request body sent to the inner service.
    Request,
    /// The response body returned by the inner service.
    Response,
}

/// How a denied active stream should be terminated.
#[derive(Debug)]
pub enum StreamRejection {
    /// Fail the body with a transport-specific error.
    Error(Box<dyn core::error::Error + Send + Sync>),
    /// End the body with transport-specific trailers.
    Trailers(HeaderMap),
}

/// Terminates streams using the host transport's error or trailer representation.
pub trait StreamRejectionResponse: Copy + Send + Sync + 'static {
    /// Terminates an active stream denied after admission.
    ///
    /// Called at most once per body, in place of the next frame, after response headers may
    /// already have been sent. Trailers are the graceful choice where the transport carries status
    /// in them, such as gRPC responses; an error aborts the stream.
    fn stream_denied(self, side: BodySide, message: &str) -> StreamRejection;
}

/// Converts admission outcomes into responses appropriate for the host transport.
///
/// The `message` argument of each method is the corresponding text from
/// [`PolicyGateLayerConfig`]; implementations choose the status and encoding around it.
pub trait RejectionResponse<A: BodyAdapter>: StreamRejectionResponse {
    /// Renders an admission denied by the authority.
    fn denied(self, body: A, message: &str) -> Response<A::Body>;
    /// Renders a request for which the policy found no subject.
    fn missing_subject(self, body: A, message: &str) -> Response<A::Body>;
    /// Renders an admission for which no authoritative verdict was available.
    fn unavailable(self, body: A, error: AdmissionUnavailable, message: &str) -> Response<A::Body>;
}

/// Standard HTTP rendering for Tower/Hyper consumers.
///
/// Renders a plain-text body with the status the outcome maps to:
///
/// | Outcome | Status |
/// | --- | --- |
/// | denied | `429 Too Many Requests` |
/// | missing subject | `400 Bad Request` |
/// | unavailable | `503 Service Unavailable` |
///
/// A stream denied after admission fails with an error carrying the denial message, since plain
/// HTTP has no trailer status.
#[derive(Clone, Copy, Debug, Default)]
pub struct HttpRejectionResponse;

impl<A: BodyAdapter> RejectionResponse<A> for HttpRejectionResponse {
    fn denied(self, body: A, message: &str) -> Response<A::Body> {
        http_response(body, StatusCode::TOO_MANY_REQUESTS, message)
    }

    fn missing_subject(self, body: A, message: &str) -> Response<A::Body> {
        http_response(body, StatusCode::BAD_REQUEST, message)
    }

    fn unavailable(
        self,
        body: A,
        _error: AdmissionUnavailable,
        message: &str,
    ) -> Response<A::Body> {
        http_response(body, StatusCode::SERVICE_UNAVAILABLE, message)
    }
}

impl StreamRejectionResponse for HttpRejectionResponse {
    fn stream_denied(self, _side: BodySide, message: &str) -> StreamRejection {
        StreamRejection::Error(Box::new(LimitExceededError(message.to_owned())))
    }
}

/// Response policy that replaces only unavailable-admission rendering.
///
/// Produced by [`PolicyGateLayer::with_unavailable_response`]; denial, missing-subject, and
/// stream rejections keep the behavior of the wrapped policy `R`.
#[derive(Clone, Copy, Debug)]
pub struct UnavailableResponseAdapter<R, U> {
    inner: R,
    unavailable: U,
}

#[derive(Clone, Copy)]
struct ResponseContext<A, R> {
    body: A,
    response: R,
}

impl<A, R, U> RejectionResponse<A> for UnavailableResponseAdapter<R, U>
where
    A: BodyAdapter,
    R: RejectionResponse<A>,
    U: Copy + Fn(AdmissionUnavailable) -> Response<A::Body> + Send + Sync + 'static,
{
    fn denied(self, body: A, message: &str) -> Response<A::Body> {
        self.inner.denied(body, message)
    }

    fn missing_subject(self, body: A, message: &str) -> Response<A::Body> {
        self.inner.missing_subject(body, message)
    }

    fn unavailable(
        self,
        _body: A,
        error: AdmissionUnavailable,
        _message: &str,
    ) -> Response<A::Body> {
        (self.unavailable)(error)
    }
}

impl<R, U> StreamRejectionResponse for UnavailableResponseAdapter<R, U>
where
    R: StreamRejectionResponse,
    U: Copy + Send + Sync + 'static,
{
    fn stream_denied(self, side: BodySide, message: &str) -> StreamRejection {
        self.inner.stream_denied(side, message)
    }
}

